//  ---------------------- EASE IN BACK ------------------------
//.                                                            .
//.                                                 =          .
//.                                                -.          .
//.                                               .-           .
//.                                               =            .
//.                                              -             .
//.                                             .-             .
//.                                             =              .
//.                                            =               .
//.                                           +                .
//.                                          +.                .
//.                                         #.                 .
//.                                        %                   .
//.                                      .@                    .
//.                                     %=                     .
//.          #*+-                     %#                       .
//.                :+@@#=.        .*@-                         .
float easeInBack(const float x)
{
    const float c1 = 1.70158;
    const float c3 = c1 + 1;

    return c3 * x * x * x - c1 * x * x;
}

//  ---------------------- EASE OUT BACK -----------------------
//.                        .@%           :%@@#:                .
//.                      +%                       .:           .
//.                    .@                                      .
//.                   %-                                       .
//.                  #.                                        .
//.                 #                                          .
//.                +                                           .
//.               =                                            .
//.              -.                                            .
//.             :.                                             .
//.            .-                                              .
//.            =                                               .
//.           -.                                               .
//.          .:                                                .
//.          -                                                 .
//.         :.                                                 .
//.                                                            .
float easeOutBack(const float x)
{
    const float c1 = 1.70158;
    const float c3 = c1 + 1;

    return 1 + c3 * glm::pow(x - 1, 3) + c1 * glm::pow(x - 1, 2.f);
}

//  ------------------- EASE IN OUT BACK -----------------------
//.                                   .=        .=-            .
//.                                  =.                        .
//.                                 =                          .
//.                                -                           .
//.                               -.                           .
//.                               =                            .
//.                              =                             .
//.                             .-                             .
//.                             -                              .
//.                            .:                              .
//.                            =                               .
//.                           :.                               .
//.                          .-                                .
//.                          =                                 .
//.                         -                                  .
//.         .:            .-                                   .
//.           .--.      :-.                                    .
float easeInOutBack(const float x)
{
    const float c1 = 1.70158;
    const float c2 = c1 * 1.525;

    return x < 0.5
      ? (glm::pow(2.f * x, 2.f) * ((c2 + 1) * 2.f * x - c2)) / 2.f
      : (glm::pow(2.f * x - 2.f, 2.f) * ((c2 + 1) * (x * 2.f - 2.f) + c2) + 2.f) / 2.f;
}


